using System.Net;
using System.Net.Sockets;
using System.Text;
using System.Text.Json;

namespace VowenLite;

// Lets Luna's sandboxed Codex run the git commands that need YOUR logins (fetch / pull / push / ls-remote) without turning the sandbox off.
// Codex's shell runs as a separate low-privilege Windows account that has no GitHub login, no Git Credential Manager and no TLS credentials, so
// anything that talks to GitHub failed there. The old GIT: hook ran such commands on the host too, but Codex never saw the output, so it couldn't
// react to a conflict or a failed pull. Now Codex runs `node vgit.js <repo> <git args>` (a generated script in its working folder) and gets the real
// output and exit code back, in the same turn:
//   node vgit.js my-app pull --no-rebase --no-edit
// The script posts to a loopback-only listener in this process, which runs git on the host as the user. Limits:
//   - any git repo on the PC (full path or project name; a folder inside a repo resolves to its root), only these git commands: fetch, pull, push, ls-remote, remote (read-only forms)
//   - no -c / --config / upload-pack / receive-pack / exec options; push never forces, deletes or mirrors, and only when the user's request says push
//   - a random token per process (baked into the script), 5 min per command, output capped
static class GitBridge
{
    static readonly object gate = new();
    static TcpListener listener;
    static string token;
    static int port;
    public static volatile bool PushOk;   // set per request by Luna: the user asked for a push
    internal static string Token => token;
    internal static int Port => port;

    // Starts the listener once and (re)writes vgit.js into Luna's working folder. Returns the script path (null if it couldn't start).
    public static string Ensure()
    {
        lock (gate)
        {
            try
            {
                string script = Path.Combine(Directory.CreateDirectory(Path.Combine(Paths.DataDir, "luna")).FullName, "vgit.js");
                if (listener == null)
                {
                    listener = new TcpListener(IPAddress.Loopback, 0);
                    listener.Start();
                    port = ((IPEndPoint)listener.LocalEndpoint).Port;
                    token = Convert.ToHexString(System.Security.Cryptography.RandomNumberGenerator.GetBytes(16));
                    Task.Run(AcceptLoop);
                    File.WriteAllText(script, Script(), new UTF8Encoding(false));
                    Luna.Log($"git bridge listening on 127.0.0.1:{port}");
                }
                else if (!File.Exists(script)) File.WriteAllText(script, Script(), new UTF8Encoding(false));
                return script;
            }
            catch (Exception ex) { Luna.Log("git bridge failed to start: " + ex.Message); return null; }
        }
    }

    static string Script() => @"// Generated by VowenLite. Usage: node vgit.js <repo folder> <git args...>   e.g. node vgit.js my-app pull --no-rebase --no-edit
const [repo, ...args] = process.argv.slice(2);
fetch('http://127.0.0.1:" + port + @"/git', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ token: '" + token + @"', repo, args }) })
  .then(r => r.json())
  .then(j => { const o = j.out || ''; process.stdout.write(o.endsWith('\n') || o === '' ? o : o + '\n'); process.exitCode = j.exit; })
  .catch(e => { console.error('git bridge unreachable: ' + e.message); process.exitCode = 2; });
";

    static async Task AcceptLoop()
    {
        while (true)
        {
            TcpClient c;
            try { c = await listener.AcceptTcpClientAsync(); }
            catch { return; }
            _ = Task.Run(() => Handle(c));
        }
    }

    static async Task Handle(TcpClient c)
    {
        using (c)
        {
            try
            {
                c.ReceiveTimeout = c.SendTimeout = 10_000;
                var ns = c.GetStream();
                var buf = new List<byte>();
                var one = new byte[4096];
                int headEnd = -1, need = 0;
                while (true)
                {
                    int n = await ns.ReadAsync(one, 0, one.Length);
                    if (n <= 0) break;
                    buf.AddRange(one.AsSpan(0, n).ToArray());
                    if (buf.Count > 2 * 1024 * 1024) return;   // vpc.js `type --file` carries the text to type
                    if (headEnd < 0)
                    {
                        string s = Encoding.ASCII.GetString(buf.ToArray());
                        int i = s.IndexOf("\r\n\r\n", StringComparison.Ordinal);
                        if (i < 0) continue;
                        headEnd = i + 4;
                        var m = System.Text.RegularExpressions.Regex.Match(s.Substring(0, i), @"(?im)^content-length:\s*(\d+)");
                        need = m.Success ? int.Parse(m.Groups[1].Value) : 0;
                    }
                    if (buf.Count >= headEnd + need) break;
                }
                if (headEnd < 0) return;
                string body = Encoding.UTF8.GetString(buf.Skip(headEnd).Take(need).ToArray());
                bool pc = Encoding.ASCII.GetString(buf.Take(Math.Min(buf.Count, 24)).ToArray()).StartsWith("POST /pc");   // vpc.js: screen control + ArtCraft (PcBridge.cs)
                bool web = Encoding.ASCII.GetString(buf.Take(Math.Min(buf.Count, 24)).ToArray()).StartsWith("POST /web");   // vweb.js: the background browser (WebBridge.cs)
                (int exit, string output) = pc ? PcBridge.Run(body) : web ? WebBridge.Run(body) : Run(body);
                byte[] json = JsonSerializer.SerializeToUtf8Bytes(new { exit, @out = output });
                byte[] head = Encoding.ASCII.GetBytes($"HTTP/1.1 200 OK\r\nContent-Type: application/json\r\nContent-Length: {json.Length}\r\nConnection: close\r\n\r\n");
                await ns.WriteAsync(head, 0, head.Length);
                await ns.WriteAsync(json, 0, json.Length);
            }
            catch { }
        }
    }

    static readonly string[] Allowed = { "fetch", "pull", "push", "ls-remote", "remote" };

    static (int, string) Run(string body)
    {
        string repo = "", shown = "";
        try
        {
            using var doc = JsonDocument.Parse(body);
            var root = doc.RootElement;
            if (root.GetProperty("token").GetString() != token) return (126, "git bridge: bad token");
            repo = root.GetProperty("repo").GetString() ?? "";
            var args = root.GetProperty("args").EnumerateArray().Select(a => a.GetString() ?? "").ToList();
            shown = string.Join(' ', args);

            if (args.Count == 0 || !Allowed.Contains(args[0])) return Deny(repo, shown, $"git bridge only runs {string.Join(", ", Allowed)} (local git commands you can run yourself).");
            foreach (var a in args.Skip(1))
            {
                string l = a.ToLowerInvariant();
                if (l == "-c" || l.StartsWith("--config") || l.Contains("upload-pack") || l.Contains("receive-pack") || l.StartsWith("--exec") || l.StartsWith("--git-dir") || l.StartsWith("--work-tree") || l.StartsWith("--receive") || l == "-o" || l.StartsWith("--push-option"))
                    return Deny(repo, shown, "that option isn't allowed through the git bridge.");
            }
            if (args[0] == "remote" && (args.Count < 2 || !(args[1] is "-v" or "get-url" or "show"))) return Deny(repo, shown, "only read-only `remote` forms (-v, get-url, show) are allowed.");
            if (args[0] == "push")
            {
                if (!PushOk) return Deny(repo, shown, "pushing needs the user to ask for it (their request didn't say push). Finish everything else, then tell them it is ready to push.");
                foreach (var a in args.Skip(1))
                {
                    string l = a.ToLowerInvariant();
                    if (l is "-f" or "-d" or "--delete" or "--mirror" or "--prune" or "--all" or "--tags" or "--force" || l.StartsWith("--force") || a.StartsWith("+") || a.StartsWith(":"))
                        return Deny(repo, shown, "force-pushes, deletions and mirror pushes are not allowed through the git bridge; the user does those themselves.");
                }
            }

            var s0 = Settings.Load();
            // Any repo on the PC: a full path (or a folder inside a repo), or a project/folder name ("my-app"). The command allowlist and the push rule still apply.
            string dir = Path.IsPathRooted(repo) && Directory.Exists(repo) ? Path.GetFullPath(repo) : (Projects.ResolveDir(repo, s0) ?? Folders.Resolve(repo, s0, out _));
            if (dir == null || !Directory.Exists(dir)) return Deny(repo, shown, $"no folder called \"{repo}\" (give the repo's full path, or a project name).");
            dir = Path.GetFullPath(dir).TrimEnd('\\');
            string top = dir;
            while (top != null && !Directory.Exists(Path.Combine(top, ".git")) && !File.Exists(Path.Combine(top, ".git"))) top = Path.GetDirectoryName(top);
            if (top == null) return Deny(repo, shown, $"{Path.GetFileName(dir)} isn't inside a git repo.");
            dir = top;

            var psi = new System.Diagnostics.ProcessStartInfo("git") { UseShellExecute = false, CreateNoWindow = true, RedirectStandardOutput = true, RedirectStandardError = true, WorkingDirectory = dir };
            foreach (var a in args) psi.ArgumentList.Add(a);
            psi.Environment["GIT_TERMINAL_PROMPT"] = "0";
            using var p = System.Diagnostics.Process.Start(psi);
            var outT = p.StandardOutput.ReadToEndAsync(); var errT = p.StandardError.ReadToEndAsync();
            if (!p.WaitForExit(300_000)) { try { p.Kill(true); } catch { } Luna.Log($"git bridge: {Path.GetFileName(dir)} git {shown} -> timed out"); return (124, "git bridge: the command ran over 5 minutes and was stopped."); }
            string o = (outT.Result + (errT.Result.Length > 0 ? (outT.Result.Length > 0 ? "\n" : "") + errT.Result : "")).Trim();
            if (o.Length > 8000) o = o.Substring(0, 3000) + "\n…[output trimmed]…\n" + o.Substring(o.Length - 4000);
            if (p.ExitCode != 0 && o.Contains("not found", StringComparison.OrdinalIgnoreCase))
            {
                // GitHub says "not found" for a private repo you can't see: usually a collaborator invite that is pending (or was removed).
                var mm = System.Text.RegularExpressions.Regex.Match(o, @"github\.com[/:]([\w.-]+/[\w.-]+?)(?:\.git)?/?['""\s]");
                o += "\n[git bridge hint] GitHub can't see this repo with the signed-in account. If it is someone else's private repo, check for a pending invitation"
                    + (mm.Success ? $" at https://github.com/{mm.Groups[1].Value}/invitations" : "") + " (or ask the owner to re-add the account). Don't retry; tell the user.";
            }
            Luna.Log($"git bridge: {Path.GetFileName(dir)} git {shown} -> exit {p.ExitCode}");
            try { if (p.ExitCode == 0 && args[0] is "pull" or "push" or "fetch") Projects.NoteGit(dir, args[0], Path.GetFileName(dir) + ": " + (o.Length > 0 ? o.Split('\n').Last().Trim() : "ok")); } catch { }
            return (p.ExitCode, o);
        }
        catch (Exception ex) { Luna.Log("git bridge error: " + ex.Message); return (125, "git bridge error: " + ex.Message); }
    }

    static (int, string) Deny(string repo, string args, string why)
    {
        Luna.Log($"git bridge: refused `{repo} git {args}`: {why}");
        return (126, "git bridge refused: " + why);
    }
}
