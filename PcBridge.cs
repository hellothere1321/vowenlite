namespace VowenLite;

// Hands and eyes for Luna's sandboxed Codex: it runs `node vpc.js <command>` (a generated script in its working folder, same loopback
// listener and token as vgit.js) and this side, which runs as the user, looks at the screen, moves the mouse, presses keys and types.
// One Codex turn can therefore look -> act -> look again, instead of guessing everything from a single screenshot.
//   node vpc.js look [screen]        screenshot of the active window (or the whole monitor) -> look.png in the working folder
//   node vpc.js click X Y [right|double]   move X Y   drag X1 Y1 X2 Y2   scroll N [X Y]      (pixels of the LAST look.png)
//   node vpc.js key ctrl+s [enter ...]     type <text> | type --file F     paste --file F
//   node vpc.js doc                  text of the document the user is in (select all + copy; caret ends at the end)
//   node vpc.js selection            the selected text          windows / focus <title part>          wait <ms>
//   node vpc.js craft <args>         EffectCraft's command-line (see Craft.cs)
// Safety: only on while a request that asked for it is running (Luna sets Enabled), a hard cap on actions per request, typing is refused in
// windows that look like sign-in / payment pages, and a real Esc key press stops everything (Dictation's key hook calls Stop).
static class PcBridge
{
    public static volatile bool Enabled;        // screen control was asked for in the running request
    public static volatile bool CraftOnly;      // only the EffectCraft command is allowed (the request didn't ask for screen control)
    static volatile bool abort;
    static int actions;
    const int MaxActions = 120;
    static readonly object gate = new();

    // What the last `look` showed: image pixel (x, y) -> screen pixel (left + x / scale, top + y / scale).
    static int shotLeft, shotTop; static double shotScale = 1; static bool haveShot;

    public static string LunaDir => Directory.CreateDirectory(Path.Combine(Paths.DataDir, "luna")).FullName;

    public static void Begin(bool control, bool craftOnly)
    {
        Enabled = control || craftOnly; CraftOnly = craftOnly && !control; abort = false; actions = 0; haveShot = false;
        if (Enabled) WriteScript();
    }
    public static void End() { Enabled = false; }

    // A real (not injected) Esc while Luna is driving the PC: stop it at once.
    public static void EscPressed()
    {
        if (!Enabled || CraftOnly || abort) return;
        abort = true;
        Luna.Log("pc bridge: Esc pressed, stopping");
        Overlay.Notice("Stopped — Luna let go of the PC", 2500, error: true);
        Luna.CancelRunning();
    }

    static void WriteScript()
    {
        try
        {
            string script = Path.Combine(LunaDir, "vpc.js");
            GitBridge.Ensure();
            File.WriteAllText(script, @"// Generated by VowenLite. node vpc.js look | click X Y | key ctrl+s | type --file F | doc | craft <args> ... (see the prompt)
const fs = require('fs');
let args = process.argv.slice(2), text = null;
const i = args.indexOf('--file');
if (i >= 0) { text = fs.readFileSync(args[i + 1], 'utf8'); args.splice(i, 2); }
fetch('http://127.0.0.1:" + GitBridge.Port + @"/pc', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ token: '" + GitBridge.Token + @"', args, text, cwd: process.cwd() }) })
  .then(r => r.json())
  .then(j => { const o = j.out || ''; process.stdout.write(o.endsWith('\n') || o === '' ? o : o + '\n'); process.exitCode = j.exit; })
  .catch(e => { console.error('pc bridge unreachable: ' + e.message); process.exitCode = 2; });
", new UTF8Encoding(false));
        }
        catch (Exception ex) { Luna.Log("pc bridge script failed: " + ex.Message); }
    }

    public const string Help =
        "SCREEN CONTROL: you can see and operate the user's PC through the host. Run these from your working folder (each prints a result; exit code 0 = ok):\n" +
        "  node vpc.js look            screenshot of the window the user is in, saved as look.png in your working folder (`look screen` = the whole monitor). Open it with your image viewing tool. A first screenshot is already attached to this request.\n" +
        "  node vpc.js click X Y       left click at pixel X Y OF THE LATEST look.png (add `right` or `double`); also `move X Y`, `drag X1 Y1 X2 Y2`, `scroll N` (N notches, negative = down; optional X Y)\n" +
        "  node vpc.js key ctrl+a      press a key or combo; several in one call run in order: `key ctrl+end enter enter`. Names: ctrl alt shift win enter tab esc space backspace delete up down left right home end pageup pagedown f1-f12, letters, digits\n" +
        "  node vpc.js type some text  types into the focused window. For anything longer than a line write it to a file first and run `node vpc.js type --file draft.txt` (`paste --file draft.txt` pastes it in one go: use that for long text)\n" +
        "  node vpc.js doc             returns the text of the document/box the user is in (it selects all, copies, and leaves the caret at the END). `selection` returns just the selected text\n" +
