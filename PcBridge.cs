    public static (int, string) Run(string body)
    {
        try
        {
            using var doc = JsonDocument.Parse(body);
            var root = doc.RootElement;
            if (root.GetProperty("token").GetString() != GitBridge.Token) return (126, "pc bridge: bad token");
            var args = root.GetProperty("args").EnumerateArray().Select(a => a.GetString() ?? "").ToList();
            string text = root.TryGetProperty("text", out var t) && t.ValueKind == JsonValueKind.String ? t.GetString() : null;
            string cwd = root.TryGetProperty("cwd", out var c) && c.ValueKind == JsonValueKind.String ? c.GetString() : LunaDir;
            if (args.Count == 0) return (2, "pc bridge: give a command (look, click, key, type, doc, windows, focus, wait, craft)");
            string cmd = args[0].ToLowerInvariant();
            if (!Enabled) return (126, "pc bridge is off: the user's request did not ask for screen control.");
            if (cmd == "craft") return Craft.Run(args.Skip(1).ToList(), cwd);
            if (CraftOnly) return (126, "screen control wasn't asked for in this request; only `craft` is available.");
            if (abort) return (130, "The user pressed Esc: stop now, do nothing more on the PC, and tell them what you had done.");
            lock (gate)
            {
                if (++actions > MaxActions) return (126, $"pc bridge: over {MaxActions} actions for one request. Stop and tell the user where things stand.");
                var r = Do(cmd, args.Skip(1).ToList(), text);
                Luna.Log($"pc bridge: {cmd} {Short(string.Join(' ', args.Skip(1)))} -> {(r.Item1 == 0 ? "ok" : "exit " + r.Item1)}");
                return r;
            }
        }
        catch (Exception ex) { Luna.Log("pc bridge error: " + ex.Message); return (125, "pc bridge error: " + ex.Message); }
    }

    internal static string Test(List<string> args)
    {
        Begin(true, false);
        string body = JsonSerializer.Serialize(new { token = GitBridge.Token, args, cwd = LunaDir });
        var (exit, o) = Run(body);
        End();
        return $"exit {exit}\n{o}";
    }

    static string Short(string s) => s.Length > 60 ? s.Substring(0, 59) + "…" : s;

    static (int, string) Do(string cmd, List<string> a, string text)
    {
        switch (cmd)
        {
            case "look": return Look(a.Count > 0 && a[0].StartsWith("s", StringComparison.OrdinalIgnoreCase));
            case "click":
            case "move":
            {
                string why = null; int x = 0, y = 0;
                if (a.Count < 2 || !Pt(a[0], a[1], out x, out y, out why)) return (2, why ?? "usage: click X Y [right|double]");
                SetCursorPos(x, y); Thread.Sleep(60);
                if (cmd == "move") return (0, "moved");
                string how = a.Count > 2 ? a[2].ToLowerInvariant() : "left";
                if (how == "right") { mouse_event(0x0008, 0, 0, 0, UIntPtr.Zero); mouse_event(0x0010, 0, 0, 0, UIntPtr.Zero); }
                else
                {
                    mouse_event(0x0002, 0, 0, 0, UIntPtr.Zero); mouse_event(0x0004, 0, 0, 0, UIntPtr.Zero);
                    if (how == "double") { Thread.Sleep(70); mouse_event(0x0002, 0, 0, 0, UIntPtr.Zero); mouse_event(0x0004, 0, 0, 0, UIntPtr.Zero); }
                }
                Thread.Sleep(180);
                return (0, "clicked. window now: " + Title());
            }
            case "drag":
            {
                string why = null; int x1 = 0, y1 = 0, x2 = 0, y2 = 0;
                if (a.Count < 4 || !Pt(a[0], a[1], out x1, out y1, out why) || !Pt(a[2], a[3], out x2, out y2, out why)) return (2, why ?? "usage: drag X1 Y1 X2 Y2");
                SetCursorPos(x1, y1); Thread.Sleep(80); mouse_event(0x0002, 0, 0, 0, UIntPtr.Zero); Thread.Sleep(80);
                for (int i = 1; i <= 8; i++) { SetCursorPos(x1 + (x2 - x1) * i / 8, y1 + (y2 - y1) * i / 8); Thread.Sleep(20); }
                mouse_event(0x0004, 0, 0, 0, UIntPtr.Zero); Thread.Sleep(150);
                return (0, "dragged");
            }
            case "scroll":
            {
                if (a.Count < 1 || !int.TryParse(a[0], out int n)) return (2, "usage: scroll N [X Y]  (negative = down)");
                if (a.Count >= 3 && Pt(a[1], a[2], out int x, out int y, out _)) { SetCursorPos(x, y); Thread.Sleep(50); }
                n = Math.Clamp(n, -40, 40);
                for (int i = 0; i < Math.Abs(n); i++) { mouse_event(0x0800, 0, 0, n > 0 ? 120 : -120, UIntPtr.Zero); Thread.Sleep(15); }
                Thread.Sleep(200);
                return (0, "scrolled");
            }
            case "key":
            {
                if (a.Count == 0) return (2, "usage: key ctrl+s [more combos]");
                foreach (var combo in a)
                {
                    var vks = new List<ushort>();
                    foreach (var part in combo.Split('+', StringSplitOptions.RemoveEmptyEntries))
                    {
                        ushort vk = Vk(part);
                        if (vk == 0) return (2, $"unknown key \"{part}\" in \"{combo}\"");
                        vks.Add(vk);
                    }
                    if (vks.Count == 0) continue;
                    Native.Combo(vks.ToArray());
                    Thread.Sleep(90);
                    if (abort) return (130, "stopped (Esc)");
                }
                return (0, "pressed");
            }
            case "type":
            case "paste":
            {
                string s = text ?? string.Join(' ', a);
                if (s.Length == 0) return (2, "nothing to type");
                string title = Title();
                if (Secret.IsMatch(title)) return (126, $"refused: the active window (\"{Short(title)}\") looks like a sign-in or payment page. The user types there themselves.");
                var set = Settings.Load();
                if (set.Humanize && s.Length > 160) s = Humanize.Clean(s, out _);
                s = s.Replace("\r", "");
                if (cmd == "paste")
                {
                    string old = Luna.ClipboardText();
                    if (!Assistant.SetClipboard(s)) return (1, "couldn't set the clipboard");
                    Thread.Sleep(80); Native.Combo(0x11, 0x56); Thread.Sleep(350);
                    if (old.Length > 0) Assistant.SetClipboard(old);
                    return (0, $"pasted {s.Length} characters");
                }
                // Typed in small pieces so Esc can interrupt and slow apps (Google Docs) keep up.
                foreach (var line in SplitKeep(s))
                {
                    if (abort) return (130, "stopped (Esc) part-way through typing");
                    if (line == "\n") { Native.Tap(0x0D); Thread.Sleep(25); continue; }
                    for (int i = 0; i < line.Length; i += 60)
                    {
                        if (abort) return (130, "stopped (Esc) part-way through typing");
                        Native.TypeText(line.Substring(i, Math.Min(60, line.Length - i)));
                        Thread.Sleep(22);
                    }
                }
                return (0, $"typed {s.Length} characters");
            }
            case "doc":
            case "selection":
            {
                string old = Luna.ClipboardText();
                Assistant.SetClipboard("");
                if (cmd == "doc") { Native.Combo(0x11, 0x41); Thread.Sleep(220); }
                Native.Combo(0x11, 0x43);
                string got = "";
                for (int i = 0; i < 20 && got.Length == 0; i++) { Thread.Sleep(80); got = Luna.ClipboardText(); }
                if (cmd == "doc") { Native.Combo(0x11, 0x23); Thread.Sleep(80); }   // Ctrl+End: drop the selection, caret at the end
                Assistant.SetClipboard(old);
                if (got.Length == 0) return (1, cmd == "doc" ? "nothing came back (the window may not be a text document, or it blocks copying). Use `look` and scroll instead." : "nothing is selected");
                got = got.Replace("\r", "");
                int total = got.Length;
                if (got.Length > 14000) got = got.Substring(0, 4000) + "\n…[" + (total - 12000) + " characters in the middle left out]…\n" + got.Substring(total - 8000);
                return (0, $"[{total} characters from \"{Short(Title())}\"" + (cmd == "doc" ? "; the caret is now at the end" : "") + "]\n" + got);
            }
            case "windows":
            {
                var list = Windows();
                return (0, "active: " + Title() + "\n" + string.Join("\n", list.Select(w => "- " + w.Title)));
            }
            case "focus":
            {
                string want = string.Join(' ', a).Trim();
                if (want.Length == 0) return (2, "usage: focus <part of a window title>");
                var hit = Windows().FirstOrDefault(w => w.Title.Contains(want, StringComparison.OrdinalIgnoreCase));
                if (hit.H == IntPtr.Zero) return (1, $"no window with \"{want}\" in its title. Run `windows` to list them.");
                if (IsIconic(hit.H)) ShowWindow(hit.H, 9);
                keybd_event(0x12, 0, 0, UIntPtr.Zero); keybd_event(0x12, 0, 2, UIntPtr.Zero);   // lets SetForegroundWindow through
                SetForegroundWindow(hit.H); Thread.Sleep(300);
                return (0, "active: " + Title());
            }
            case "wait":
            {
                int ms = a.Count > 0 && int.TryParse(a[0], out int v) ? Math.Clamp(v, 50, 5000) : 500;
                Thread.Sleep(ms);
                return (0, "waited");
            }
        }
        return (2, $"pc bridge: unknown command \"{cmd}\" (look, click, move, drag, scroll, key, type, paste, doc, selection, windows, focus, wait, craft)");
    }

    static readonly Regex Secret = new(@"\b(password|passcode|sign[ -]?in|log[ -]?in|checkout|payment|pay now|billing|bank|2fa|verification code|credit card)\b", RegexOptions.IgnoreCase);

    static IEnumerable<string> SplitKeep(string s)
    {
        int start = 0;
        for (int i = 0; i < s.Length; i++)
            if (s[i] == '\n') { if (i > start) yield return s.Substring(start, i - start); yield return "\n"; start = i + 1; }
        if (start < s.Length) yield return s.Substring(start);
    }

    static (int, string) Look(bool screen)
    {
        string png = Path.Combine(LunaDir, "look.png"), meta = png + ".txt";
        try { File.Delete(meta); } catch { }
        var psi = new ProcessStartInfo(Environment.ProcessPath) { UseShellExecute = false, CreateNoWindow = true };
        psi.ArgumentList.Add("--shot"); psi.ArgumentList.Add(png); psi.ArgumentList.Add("--meta"); psi.ArgumentList.Add("--max"); psi.ArgumentList.Add("1400");
        if (screen) psi.ArgumentList.Add("--screen");
        using var p = Process.Start(psi);
        if (p == null || !p.WaitForExit(8000) || !File.Exists(meta)) { try { p?.Kill(); } catch { } return (1, "the screenshot failed"); }
        return (0, NoteShot(meta) + " Saved as look.png in your working folder: open it with your image viewing tool.");
    }

    // Reads "<left> <top> <width> <height> <imgW> <imgH>" written by `--shot --meta` and remembers the mapping for clicks.
    public static string NoteShot(string metaFile)
    {
        try
        {
            var n = File.ReadAllText(metaFile).Trim().Split(' ').Select(int.Parse).ToArray();
            shotLeft = n[0]; shotTop = n[1]; shotScale = (double)n[4] / Math.Max(1, n[2]); haveShot = true;
            return $"Screenshot {n[4]}x{n[5]} px of \"{Short(Title())}\". Click coordinates are pixels in this image.";
        }
        catch { return "Screenshot taken."; }
    }

    static bool Pt(string sx, string sy, out int x, out int y, out string why)
    {
        x = y = 0; why = null;
        if (!double.TryParse(sx, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out double ix) ||
            !double.TryParse(sy, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out double iy)) { why = "coordinates must be numbers"; return false; }
        if (!haveShot) { why = "run `look` first: coordinates are pixels of the latest screenshot"; return false; }
        x = shotLeft + (int)Math.Round(ix / shotScale); y = shotTop + (int)Math.Round(iy / shotScale);
        return true;
    }

    static ushort Vk(string name)
    {
        string n = name.Trim().ToLowerInvariant();
        if (n.Length == 1)
        {
            char ch = n[0];
            if (ch is >= 'a' and <= 'z') return (ushort)(ch - 'a' + 0x41);
            if (ch is >= '0' and <= '9') return (ushort)ch;
        }
        var f = Regex.Match(n, @"^f(\d{1,2})$");
        if (f.Success && int.Parse(f.Groups[1].Value) is >= 1 and <= 12) return (ushort)(0x6F + int.Parse(f.Groups[1].Value));
        return n switch
        {
            "ctrl" or "control" => 0x11, "alt" => 0x12, "shift" => 0x10, "win" or "windows" or "cmd" or "meta" => 0x5B,
            "enter" or "return" => 0x0D, "tab" => 0x09, "esc" or "escape" => 0x1B, "space" or "spacebar" => 0x20,
            "backspace" or "back" => 0x08, "delete" or "del" => 0x2E, "insert" => 0x2D,
            "up" => 0x26, "down" => 0x28, "left" => 0x25, "right" => 0x27,
            "home" => 0x24, "end" => 0x23, "pageup" or "pgup" => 0x21, "pagedown" or "pgdn" => 0x22,
            "," or "comma" => 0xBC, "." or "period" => 0xBE, "/" or "slash" => 0xBF, "-" or "minus" => 0xBD, "=" or "plus" or "equals" => 0xBB,
            ";" => 0xBA, "'" => 0xDE, "[" => 0xDB, "]" => 0xDD, "\\" => 0xDC, "`" => 0xC0,
            _ => 0,
        };
    }

    static string Title()
    {
        var sb = new StringBuilder(300);
        GetWindowText(GetForegroundWindow(), sb, sb.Capacity);
        return sb.ToString();
    }

    static List<(IntPtr H, string Title)> Windows()
    {
        var list = new List<(IntPtr, string)>();
        EnumWindows((h, _) =>
        {
            if (!IsWindowVisible(h)) return true;
            var sb = new StringBuilder(300);
            GetWindowText(h, sb, sb.Capacity);
            string t = sb.ToString().Trim();
            if (t.Length > 0 && t != "Program Manager" && !t.StartsWith("VowenLite overlay")) list.Add((h, t));
            return true;
        }, IntPtr.Zero);
        return list.Take(40).ToList();
    }

